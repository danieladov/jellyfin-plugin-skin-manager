/*
 * Skin Manager configuration page controller.
 *
 * Loaded by jellyfin-web through data-controller="__plugin/skinmanager.js".
 * jellyfin-web calls the default export once for every new instance of the page,
 * so the page initialises correctly every time it is opened (not only on a full reload).
 */

const PLUGIN_ID = 'e9ca8b8e-ca6d-40e7-85dc-58e536df8eb3';

// Every stylesheet written by this version starts with this header. It lets us tell our own
// output apart from CSS the user wrote by hand, so we never silently throw theirs away.
const HEADER_PREFIX = '/* ==== Skin Manager';
const CUSTOM_SECTION = '/* ==== Skin Manager: your custom CSS ==== */';

const IMPORT_REGEX = /@import\s+[^;]+;/gi;

let libsPromise = null;

function pageUrl(name) {
    return ApiClient.getUrl('web/ConfigurationPage', { name: name });
}

/** Loads the bundled jQuery plugins (font picker + spectrum colour picker) once per session. */
function loadLibs() {
    const $ = window.jQuery;
    if (!$) {
        return Promise.reject(new Error('jQuery is not available in this version of jellyfin-web'));
    }
    if ($.fn.spectrum && $.fn.fontpicker) {
        return Promise.resolve();
    }
    if (!libsPromise) {
        libsPromise = new Promise(function (resolve, reject) {
            const script = document.createElement('script');
            script.src = pageUrl('skinmanager.fontpicker.js');
            script.onload = resolve;
            script.onerror = function () {
                libsPromise = null;
                reject(new Error('Failed to load ' + script.src));
            };
            document.head.appendChild(script);
        });
    }
    return libsPromise;
}

function loadSkins() {
    return fetch(pageUrl('skinmanager.skins.json')).then(function (response) {
        if (!response.ok) {
            throw new Error('Could not load the skin list (HTTP ' + response.status + ')');
        }
        return response.json();
    });
}

function escapeHtml(value) {
    return String(value == null ? '' : value)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

function replaceToken(css, value) {
    return (css || '').split('$').join(value);
}

/** Splits CSS into its @import statements and everything else. */
function splitImports(css) {
    const imports = (css || '').match(IMPORT_REGEX) || [];
    const rest = (css || '').replace(IMPORT_REGEX, '').trim();
    return { imports: imports.map(function (i) { return i.trim(); }), rest: rest };
}

function isGeneratedCss(css) {
    return (css || '').trimStart().indexOf(HEADER_PREFIX) === 0;
}

/**
 * Builds the final branding stylesheet. Browsers ignore @import rules that come after any
 * other rule, so every @import (skin, options, fonts and the user's own) is hoisted to the top.
 */
function composeCss(skinName, skinCss, customCss) {
    const skin = splitImports(skinCss);
    const custom = splitImports(customCss);
    const imports = [];
    skin.imports.concat(custom.imports).forEach(function (statement) {
        if (imports.indexOf(statement) === -1) {
            imports.push(statement);
        }
    });

    const parts = [
        HEADER_PREFIX + ': ' + (skinName || 'Default') + ' ==== */',
        '/* Generated by the Skin Manager plugin. Changes made here are overwritten the next time',
        '   a skin is set; put your own CSS in the "Custom CSS" box of the plugin instead. */'
    ];
    if (imports.length) {
        parts.push(imports.join('\n'));
    }
    if (skin.rest) {
        parts.push(skin.rest);
    }
    if (custom.rest) {
        parts.push(CUSTOM_SECTION, custom.rest);
    }
    return parts.join('\n') + '\n';
}

function getSavedValues(config) {
    // options is stored as [css, value, css, value, ...]; several options may share the same css,
    // so keep the values per key in order.
    const saved = new Map();
    const list = config.options || [];
    for (let i = 0; i + 1 < list.length; i += 2) {
        if (!saved.has(list[i])) {
            saved.set(list[i], []);
        }
        saved.get(list[i]).push(list[i + 1]);
    }
    return {
        take: function (css) {
            const values = saved.get(css);
            return values && values.length ? values.shift() : undefined;
        }
    };
}

function colorToCss(color, mode) {
    if (!color) {
        return '';
    }
    const rgb = color.toRgb();
    switch (mode) {
        case 'hex':
            return color.toHexString();
        case 'only_numbers':
            return rgb.r + ',' + rgb.g + ',' + rgb.b;
        default:
            return 'rgba(' + rgb.r + ',' + rgb.g + ',' + rgb.b + ',' + rgb.a + ')';
    }
}

const SPECTRUM_PALETTE = [
    ['rgb(0, 0, 0)', 'rgb(67, 67, 67)', 'rgb(102, 102, 102)', 'rgb(204, 204, 204)', 'rgb(217, 217, 217)', 'rgb(255, 255, 255)'],
    ['rgb(152, 0, 0)', 'rgb(255, 0, 0)', 'rgb(255, 153, 0)', 'rgb(255, 255, 0)', 'rgb(0, 255, 0)',
        'rgb(0, 255, 255)', 'rgb(74, 134, 232)', 'rgb(0, 0, 255)', 'rgb(153, 0, 255)', 'rgb(255, 0, 255)'],
    ['rgb(98, 121, 205)', 'rgb(0, 164, 220)', 'rgb(170, 92, 195)', 'rgb(224, 102, 102)', 'rgb(246, 178, 107)',
        'rgb(255, 217, 102)', 'rgb(147, 196, 125)', 'rgb(118, 165, 175)', 'rgb(111, 168, 220)', 'rgb(194, 123, 160)']
];

/**
 * One control per skin option. Each knows how to render itself, read its value (for saving)
 * and produce its CSS (for applying).
 */
function createControl(option, index, savedValue) {
    const id = 'smOption' + index;
    const name = escapeHtml(option.name);
    const description = option.description
        ? '<div class="fieldDescription">' + escapeHtml(option.description) + '</div>'
        : '';
    const preview = option.preview
        ? '<a class="smPreviewLink" href="' + escapeHtml(option.preview) + '" target="_blank" rel="noopener">preview</a>'
        : '';
    const hasSaved = savedValue !== undefined && savedValue !== null;
    const control = { option: option, id: id };

    switch (option.type) {
        case 'checkBox': {
            const checked = hasSaved ? savedValue === 'true' : option.default === true || option.default === 'true';
            control.html = '<div class="checkboxContainer checkboxContainer-withDescription">'
                + '<label><input is="emby-checkbox" type="checkbox" id="' + id + '"' + (checked ? ' checked' : '') + ' />'
                + '<span>' + name + '</span></label>' + preview
                + (option.description ? '<div class="fieldDescription checkboxFieldDescription">' + escapeHtml(option.description) + '</div>' : '')
                + '</div>';
            control.value = function (view) { return view.querySelector('#' + id).checked ? 'true' : 'false'; };
            control.css = function (view) { return view.querySelector('#' + id).checked ? option.css : ''; };
            break;
        }
        case 'selector': {
            const selections = option.selections || [];
            let selected = 0;
            selections.forEach(function (selection, i) {
                if (hasSaved ? selection.name === savedValue : selection.name === option.default) {
                    selected = i;
                }
            });
            control.html = '<div class="selectContainer">'
                + '<label class="selectLabel" for="' + id + '">' + name + '</label>' + preview
                + '<select class="emby-select emby-select-withcolor" id="' + id + '">'
                + selections.map(function (selection, i) {
                    return '<option value="' + i + '"' + (i === selected ? ' selected' : '') + '>' + escapeHtml(selection.name) + '</option>';
                }).join('')
                + '</select><div class="selectArrowContainer"><div style="visibility:hidden;display:none;">0</div>'
                + '<span class="selectArrow material-icons keyboard_arrow_down" aria-hidden="true"></span></div>'
                + description + '</div>';
            const current = function (view) { return selections[view.querySelector('#' + id).selectedIndex]; };
            control.value = function (view) { const s = current(view); return s ? s.name : ''; };
            control.css = function (view) { const s = current(view); return s ? (s.css || '') : ''; };
            break;
        }
        case 'colorPicker': {
            const initial = hasSaved ? savedValue : (option.default || '');
            control.html = '<div class="inputContainer">'
                + '<label class="inputLabel" for="' + id + '">' + name + '</label>' + preview
                + '<div><input type="text" class="smColor" id="' + id + '" value="' + escapeHtml(initial) + '" /></div>'
                + description + '</div>';
            control.init = function (view) {
                window.jQuery(view.querySelector('#' + id)).spectrum({
                    color: initial || null,
                    allowEmpty: true,
                    showInput: true,
                    showInitial: true,
                    showPalette: true,
                    showAlpha: true,
                    showSelectionPalette: true,
                    maxSelectionSize: 10,
                    preferredFormat: 'hex',
                    localStorageKey: 'skinmanager.spectrum',
                    palette: SPECTRUM_PALETTE
                });
            };
            const get = function (view) {
                const input = view.querySelector('#' + id);
                if (window.jQuery && window.jQuery.fn.spectrum) {
                    return window.jQuery(input).spectrum('get');
                }
                // Colour picker library failed to load: fall back to whatever was typed in the box.
                return input.value && window.tinycolor ? window.tinycolor(input.value) : null;
            };
            control.value = function (view) { const c = get(view); return c ? c.toString() : ''; };
            control.css = function (view) {
                const color = colorToCss(get(view), option.mode);
                // An empty colour (e.g. Monochromic's optional accent) means "leave the skin's default".
                return color ? replaceToken(option.css, color) : '';
            };
            break;
        }
        case 'number':
        case 'text': {
            const initial = hasSaved ? savedValue : (option.default == null ? '' : option.default);
            const attrs = option.type === 'number'
                ? ' type="number" step="' + escapeHtml(option.step || 1) + '"'
                    + (option.min != null ? ' min="' + escapeHtml(option.min) + '"' : '')
                    + (option.max != null ? ' max="' + escapeHtml(option.max) + '"' : '')
                : ' type="text"';
            control.html = '<div class="inputContainer">'
                + '<label class="inputLabel inputLabelUnfocused" for="' + id + '">' + name + '</label>' + preview
                + '<input class="emby-input" id="' + id + '"' + attrs + ' value="' + escapeHtml(initial) + '" />'
                + description + '</div>';
            control.value = function (view) { return view.querySelector('#' + id).value; };
            control.css = function (view) {
                const value = view.querySelector('#' + id).value;
                return value === '' ? '' : replaceToken(option.css, value);
            };
            break;
        }
        case 'slider':
        case 'blurSlider': {
            const isBlur = option.type === 'blurSlider';
            const initial = hasSaved ? savedValue : (option.default == null ? 0 : option.default);
            const max = option.max != null ? option.max : (isBlur ? 40 : 300);
            control.html = '<div class="inputContainer">'
                + '<label class="inputLabel" for="' + id + '">' + name + ': <span id="' + id + 'Value">' + escapeHtml(initial) + '</span></label>' + preview
                + '<input type="range" class="smSlider" id="' + id + '" min="' + escapeHtml(option.min || 0) + '" max="' + escapeHtml(max)
                + '" step="' + escapeHtml(option.step || 1) + '" value="' + escapeHtml(initial) + '" />'
                + description
                + (isBlur ? '<div class="smBlurPreview"><img id="' + id + 'Image" alt="" src="https://i.imgur.com/sMDQSdV.png" /></div>' : '')
                + '</div>';
            control.init = function (view) {
                const input = view.querySelector('#' + id);
                const update = function () {
                    view.querySelector('#' + id + 'Value').textContent = input.value;
                    if (isBlur) {
                        view.querySelector('#' + id + 'Image').style.filter = 'blur(' + input.value + 'px)';
                    }
                };
                input.addEventListener('input', update);
                update();
            };
            control.value = function (view) { return view.querySelector('#' + id).value; };
            control.css = function (view) { return replaceToken(option.css, view.querySelector('#' + id).value); };
            break;
        }
        case 'googleFonts': {
            const initial = hasSaved ? savedValue : (option.default || '');
            control.html = '<div class="inputContainer">'
                + '<label class="inputLabel" for="' + id + '">' + name + '</label>'
                + '<div><input type="text" class="smFont" id="' + id + '" value="' + escapeHtml(initial) + '" /></div>'
                + '<button is="emby-button" type="button" class="raised button-cancel smClearFont" data-target="' + id + '"><span>Use the skin\'s font</span></button>'
                + description + '</div>';
            control.init = function (view) {
                const $input = window.jQuery(view.querySelector('#' + id));
                // Only Google fonts: the picker's "local" fonts would need .woff files we do not ship.
                $input.fontpicker({ variants: false, localFonts: {}, parentElement: view });
                view.querySelector('.smClearFont[data-target="' + id + '"]').addEventListener('click', function () {
                    $input.val('').trigger('change');
                    const label = view.querySelector('#' + id).parentNode.querySelector('.fp-fontspec');
                    if (label) {
                        label.textContent = '';
                    }
                });
            };
            control.value = function (view) { return view.querySelector('#' + id).value; };
            control.css = function (view) {
                const family = view.querySelector('#' + id).value.trim();
                if (!family) {
                    return '';
                }
                const url = 'https://fonts.googleapis.com/css?family=' + encodeURIComponent(family).replace(/%20/g, '+') + '&display=swap';
                return "@import url('" + url + "');\n" + replaceToken(option.css, family.replace(/\+/g, ' '));
            };
            break;
        }
        default:
            console.warn('[SkinManager] Unsupported option type: ' + option.type);
            return null;
    }
    return control;
}

export default function (view) {
    let skins = [];
    let config = null;
    let controls = [];

    const skinSelect = view.querySelector('#smSkin');
    const optionsContainer = view.querySelector('#smOptions');
    const previewsContainer = view.querySelector('#smPreviews');
    const customCssInput = view.querySelector('#smCustomCss');
    const generatedOutput = view.querySelector('#smGeneratedCss');

    function currentSkin() {
        return skins[skinSelect.selectedIndex];
    }

    function renderSkin(saved) {
        const skin = currentSkin();
        controls = [];
        view.querySelector('#smDescription').textContent = skin
            ? (skin.description || '') + (skin.author ? ' (by ' + skin.author + ')' : '')
            : '';

        let html = '';
        let index = 0;
        (skin ? skin.categories || [] : []).forEach(function (category) {
            const categoryControls = [];
            (category.options || []).forEach(function (option) {
                const control = createControl(option, index++, saved ? saved.take(option.css) : undefined);
                if (control) {
                    categoryControls.push(control);
                    controls.push(control);
                }
            });
            if (categoryControls.length) {
                html += '<fieldset class="verticalSection verticalSection-extrabottompadding smCategory">'
                    + '<legend>' + escapeHtml(category.name) + '</legend>'
                    + categoryControls.map(function (c) { return c.html; }).join('')
                    + '</fieldset>';
            }
        });
        optionsContainer.innerHTML = html;
        controls.forEach(function (control) {
            if (control.init) {
                try {
                    control.init(view);
                } catch (err) {
                    console.error('[SkinManager] Failed to initialise option ' + control.option.name, err);
                }
            }
        });

        previewsContainer.innerHTML = skin && skin.previews && skin.previews.length
            ? '<h2 class="sectionTitle">Previews</h2>' + skin.previews.map(function (p) {
                return '<figure class="smPreview"><img loading="lazy" alt="" src="' + escapeHtml(p.url) + '" />'
                    + '<figcaption>' + escapeHtml(p.name) + '</figcaption></figure>';
            }).join('')
            : '';

        generatedOutput.value = '';
        view.querySelector('#smGeneratedContainer').classList.add('hide');
    }

    function buildSkinCss() {
        const skin = currentSkin();
        if (!skin) {
            return '';
        }
        const parts = [skin.defaultCss || ''];
        controls.forEach(function (control) {
            const css = control.css(view);
            if (css) {
                parts.push(css);
            }
        });
        return parts.join('\n');
    }

    function collectOptions() {
        const options = [];
        controls.forEach(function (control) {
            options.push(control.option.css || '', control.value(view));
        });
        return options;
    }

    function renderBackup() {
        const container = view.querySelector('#smBackupContainer');
        const hasBackup = !!(config && config.previousCss);
        container.classList.toggle('hide', !hasBackup);
        view.querySelector('#smBackupCss').value = hasBackup ? config.previousCss : '';
    }

    function saveConfig() {
        return ApiClient.updatePluginConfiguration(PLUGIN_ID, config);
    }

    /** Writes the branding CSS, backing up hand-written CSS the first time we replace it. */
    function writeBrandingCss(css) {
        return ApiClient.getNamedConfiguration('branding').then(function (branding) {
            const existing = branding.CustomCss || '';
            if (existing.trim() && !isGeneratedCss(existing) && !config.previousCss) {
                config.previousCss = existing;
            }
            branding.CustomCss = css;
            return ApiClient.updateNamedConfiguration('branding', branding);
        });
    }

    function apply(skinName, skinCss) {
        Dashboard.showLoadingMsg();
        config.customCss = customCssInput.value;
        const css = composeCss(skinName, skinCss, config.customCss);
        return writeBrandingCss(css)
            .then(saveConfig)
            .then(function () {
                Dashboard.hideLoadingMsg();
                Dashboard.processPluginConfigurationUpdateResult();
                // The web client caches branding options, reload so the new CSS takes effect.
                setTimeout(function () { window.location.reload(); }, 600);
            })
            .catch(function (err) {
                Dashboard.hideLoadingMsg();
                console.error('[SkinManager] Failed to apply skin', err);
                Dashboard.alert({ title: 'Skin Manager', message: 'Failed to apply the skin: ' + (err && err.message ? err.message : err) });
            });
    }

    function onSetSkin() {
        const skin = currentSkin();
        config.selectedSkin = skin ? skin.name : '';
        config.options = collectOptions();
        apply(skin ? skin.name : '', buildSkinCss());
    }

    function onRemoveSkin() {
        config.selectedSkin = '';
        config.options = [];
        skinSelect.selectedIndex = Math.max(0, skins.findIndex(function (s) { return !s.defaultCss; }));
        renderSkin(null);
        apply('Default', '');
    }

    function onShowCss() {
        const container = view.querySelector('#smGeneratedContainer');
        const skin = currentSkin();
        generatedOutput.value = composeCss(skin ? skin.name : '', buildSkinCss(), customCssInput.value);
        container.classList.remove('hide');
    }

    function onRestoreBackup() {
        const backup = config.previousCss || '';
        customCssInput.value = customCssInput.value.trim()
            ? customCssInput.value.replace(/\s+$/, '') + '\n\n' + backup
            : backup;
        Dashboard.alert({
            title: 'Skin Manager',
            message: 'Your previous CSS was copied into the Custom CSS box. Remove anything you do not want (for example CSS from an old skin), then click "Set skin".'
        });
    }

    function onDiscardBackup() {
        config.previousCss = '';
        saveConfig().then(renderBackup);
    }

    function findSavedSkinIndex() {
        const selected = config.selectedSkin || '';
        // Newer configs store the skin name; 2.x stored the skin's defaultCss.
        let index = skins.findIndex(function (s) { return s.name === selected; });
        if (index === -1) {
            index = skins.findIndex(function (s) { return (s.defaultCss || '') === selected; });
        }
        return index;
    }

    function init() {
        Dashboard.showLoadingMsg();
        Promise.all([
            loadSkins(),
            ApiClient.getPluginConfiguration(PLUGIN_ID),
            loadLibs().catch(function (err) {
                console.error('[SkinManager]', err);
            })
        ]).then(function (results) {
            skins = Array.isArray(results[0]) ? results[0] : [];
            config = results[1] || {};
            config.options = config.options || [];
            config.customCss = config.customCss || '';
            config.previousCss = config.previousCss || '';

            skinSelect.innerHTML = skins.map(function (skin, i) {
                return '<option value="' + i + '">' + escapeHtml(skin.name) + '</option>';
            }).join('');
            const savedIndex = findSavedSkinIndex();
            skinSelect.selectedIndex = savedIndex === -1 ? 0 : savedIndex;
            customCssInput.value = config.customCss;

            renderSkin(savedIndex === -1 ? null : getSavedValues(config));
            renderBackup();
            Dashboard.hideLoadingMsg();
        }).catch(function (err) {
            Dashboard.hideLoadingMsg();
            console.error('[SkinManager] Failed to load', err);
            view.querySelector('#smDescription').textContent = 'Failed to load Skin Manager: ' + (err && err.message ? err.message : err);
        });
    }

    skinSelect.addEventListener('change', function () {
        // Restore saved values when switching back to the skin that is currently applied.
        renderSkin(skinSelect.selectedIndex === findSavedSkinIndex() ? getSavedValues(config) : null);
    });
    view.querySelector('#smSetSkin').addEventListener('click', onSetSkin);
    view.querySelector('#smRemoveSkin').addEventListener('click', onRemoveSkin);
    view.querySelector('#smShowCss').addEventListener('click', onShowCss);
    view.querySelector('#smRestoreBackup').addEventListener('click', onRestoreBackup);
    view.querySelector('#smDiscardBackup').addEventListener('click', onDiscardBackup);
    view.querySelector('form').addEventListener('submit', function (e) {
        e.preventDefault();
        return false;
    });

    view.addEventListener('viewshow', init);
}
